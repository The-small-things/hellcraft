#!/usr/bin/env python3
"""Turns the Blockbench models in versions/26.3/art (*.bbmodel) into game code. For a model "minos":

- client/render/gen/MinosMesh.java: the jointed model (Minecraft's LayerDefinition), one part per bone;
- client/render/gen/MinosAnimations.java: each animation as an AnimationDefinition (Minecraft's own keyframes);
- entity/boss/gen/MinosAnim.java (common code): the animations' lengths and named events, which the server times
  its blows by;
- assets/hellcraft/textures/entity/minos.png (and minos_glow.png, the parts that shine in the dark).

Run from the repo root:  python3 tools/gen_bosses.py   (after tools/art/<model>.py, which writes the .bbmodel)

Blockbench's space is Y up with the model's right hand at +X; Minecraft's model space is Y down with its left hand at
+X (the two differ by a half turn about Z). So positions map (x, y, z) -> (-x, -y, z), with feet at y = 24, and
rotations (rx, ry, rz) -> (-rx, -ry, rz), the order (Z, then Y, then X) unchanged. Blockbench's Java export does the
same, so the game shows what Blockbench shows.
"""
import base64
import glob
import json
import os

ROOT = os.path.join(os.path.dirname(__file__), "..", "versions", "26.3")
ART = os.path.join(ROOT, "art")
CLIENT = os.path.join(ROOT, "src", "client", "java", "net", "thesmallthings", "hellcraft", "client", "render", "gen")
COMMON = os.path.join(ROOT, "src", "main", "java", "net", "thesmallthings", "hellcraft", "entity", "boss", "gen")
TEXTURES = os.path.join(ROOT, "src", "main", "resources", "assets", "hellcraft", "textures", "entity")
HEADER = "// Generated by tools/gen_bosses.py from art/{src}: edit the model (tools/art), not this file."
INTERPOLATIONS = {"catmullrom": "CATMULLROM", "linear": "LINEAR", "step": "LINEAR", "bezier": "CATMULLROM"}


def f(v):
    """A Java float literal."""
    v = float(v)
    if abs(v) < 5e-7:
        v = 0.0
    s = f"{v:.4f}".rstrip("0").rstrip(".")
    if s in ("-0", ""):
        s = "0"
    return s + "F"


def num(v):
    """Blockbench stores keyframe values as numbers or (Molang) strings; plain numbers are all we use."""
    if isinstance(v, (int, float)):
        return float(v)
    v = str(v).strip()
    return float(v) if v else 0.0


def camel(name):
    return "".join(part[:1].upper() + part[1:] for part in name.replace("-", "_").split("_"))


def constant(name):
    return name.upper().replace("-", "_").replace(".", "_")


def write(path, text):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w") as out:
        out.write(text)


class Converter:
    def __init__(self, path):
        self.src = os.path.basename(path)
        with open(path) as fh:
            self.doc = json.load(fh)
        self.name = self.doc["name"]
        self.java = camel(self.name)
        self.elements = {e["uuid"]: e for e in self.doc["elements"]}
        self.width = self.doc["resolution"]["width"]
        self.height = self.doc["resolution"]["height"]
        self.part_names = set()
        self.lines = []

    # ---------------------------------------------------------------------------------------------- the mesh

    def unique(self, name):
        assert name not in self.part_names, f"{self.src}: two parts named {name}"
        self.part_names.add(name)
        return name

    def box(self, e, pivot):
        """One cube's builder call, relative to the pivot of the part that holds it."""
        frm, to = e["from"], e["to"]
        size = [to[i] - frm[i] for i in range(3)]
        x = pivot[0] - to[0]
        y = pivot[1] - to[1]
        z = frm[2] - pivot[2]
        u, v = e.get("uv_offset", [0, 0])
        inflate = e.get("inflate", 0) or 0
        mirror = ".mirror()" if e.get("mirror_uv") else ".mirror(false)"
        deform = f", new CubeDeformation({f(inflate)})" if inflate else ""
        return f".texOffs({int(u)}, {int(v)}){mirror}.addBox({f(x)}, {f(y)}, {f(z)}, {f(size[0])}, {f(size[1])}, {f(size[2])}{deform})"

    @staticmethod
    def pose(origin, parent, rotation):
        ox, oy, oz = (-(origin[0] - parent[0]), -(origin[1] - parent[1]), origin[2] - parent[2])
        rx, ry, rz = rotation or (0, 0, 0)
        if any(abs(r) > 1e-9 for r in (rx, ry, rz)):
            return (f"PartPose.offsetAndRotation({f(ox)}, {f(oy)}, {f(oz)}, {f(-rx * 3.141592653589793 / 180)}, "
                    f"{f(-ry * 3.141592653589793 / 180)}, {f(rz * 3.141592653589793 / 180)})")
        return f"PartPose.offset({f(ox)}, {f(oy)}, {f(oz)})"

    def group(self, g, parent_var, parent_pivot):
        name = self.unique(g["name"])
        var = "p_" + name
        pivot = g["origin"]
        plain = []
        rotated = []
        subgroups = []
        for child in g.get("children", []):
            if isinstance(child, dict):
                subgroups.append(child)
            else:
                e = self.elements[child]
                (rotated if any(abs(r) > 1e-9 for r in e.get("rotation", [0, 0, 0])) else plain).append(e)
        cubes = "CubeListBuilder.create()" + "".join(self.box(e, pivot) for e in plain)
        self.lines.append(f"\t\tPartDefinition {var} = {parent_var}.addOrReplaceChild(\"{name}\", {cubes},\n"
                          f"\t\t\t\t{self.pose(pivot, parent_pivot, g.get('rotation'))});")
        for e in rotated:
            # Minecraft can't turn a single cube, so a turned cube becomes a part of its own (as in Blockbench's export)
            part = self.unique(e["name"] + "_r")
            origin = e.get("origin", pivot)
            self.lines.append(f"\t\t{var}.addOrReplaceChild(\"{part}\", CubeListBuilder.create(){self.box(e, origin)},\n"
                              f"\t\t\t\t{self.pose(origin, pivot, e.get('rotation'))});")
        for sub in subgroups:
            self.group(sub, var, pivot)

    def mesh(self):
        for g in self.doc["outliner"]:
            if isinstance(g, dict):
                self.group(g, "root", [0, 24, 0])
            else:
                raise SystemExit(f"{self.src}: cube {self.elements[g]['name']} is outside every bone")
        body = "\n".join(self.lines)
        return f"""package net.thesmallthings.hellcraft.client.render.gen;

{HEADER.format(src=self.src)}

import net.minecraft.client.model.geom.PartPose;
import net.minecraft.client.model.geom.builders.CubeDeformation;
import net.minecraft.client.model.geom.builders.CubeListBuilder;
import net.minecraft.client.model.geom.builders.LayerDefinition;
import net.minecraft.client.model.geom.builders.MeshDefinition;
import net.minecraft.client.model.geom.builders.PartDefinition;

/** {self.java}'s jointed model: one part per bone of art/{self.src}. */
@SuppressWarnings("unused")
public final class {self.java}Mesh {{
	private {self.java}Mesh() {{
	}}

	public static final int TEXTURE_WIDTH = {self.width};
	public static final int TEXTURE_HEIGHT = {self.height};

	public static LayerDefinition createLayer() {{
		MeshDefinition mesh = new MeshDefinition();
		PartDefinition root = mesh.getRoot();
{body}
		return LayerDefinition.create(mesh, TEXTURE_WIDTH, TEXTURE_HEIGHT);
	}}
}}
"""

    # ---------------------------------------------------------------------------------------------- animations

    def anim_name(self, a):
        n = a["name"]
        prefix = f"animation.{self.name}."
        return n[len(prefix):] if n.startswith(prefix) else n.split(".")[-1]

    def animations(self):
        defs = []
        common = []
        cases = []
        for a in self.doc.get("animations", []):
            name = self.anim_name(a)
            const = constant(name)
            length = float(a["length"])
            loop = a.get("loop") == "loop"
            chains = []
            events = []
            for key, animator in sorted(a.get("animators", {}).items(), key=lambda kv: kv[1]["name"]):
                if animator.get("type") == "effect":
                    for k in animator["keyframes"]:
                        if k["channel"] == "timeline":
                            for dp in k["data_points"]:
                                script = str(dp.get("script", "")).strip()
                                if script:
                                    events.append((float(k["time"]), script))
                    continue
                bone = animator["name"]
                assert bone in self.part_names, f"{self.src}: {name} moves {bone}, which isn't a part"
                for channel, target in (("rotation", "ROTATION"), ("position", "POSITION"), ("scale", "SCALE")):
                    keys = sorted((k for k in animator["keyframes"] if k["channel"] == channel), key=lambda k: float(k["time"]))
                    if not keys:
                        continue
                    frames = []
                    for k in keys:
                        dp = k["data_points"][0]
                        x, y, z = num(dp.get("x", 0)), num(dp.get("y", 0)), num(dp.get("z", 0))
                        if channel == "rotation":
                            vec = f"KeyframeAnimations.degreeVec({f(-x)}, {f(-y)}, {f(z)})"
                        elif channel == "position":
                            vec = f"KeyframeAnimations.posVec({f(-x)}, {f(y)}, {f(z)})"
                        else:
                            vec = f"KeyframeAnimations.scaleVec({x}, {y}, {z})"
                        interp = INTERPOLATIONS.get(k.get("interpolation", "linear"), "LINEAR")
                        frames.append(f"\t\t\t\t\tnew Keyframe({f(k['time'])}, {vec}, AnimationChannel.Interpolations.{interp})")
                    chains.append(f"\t\t\t.addAnimation(\"{bone}\", new AnimationChannel(AnimationChannel.Targets.{target},\n"
                                  + ",\n".join(frames) + "))")
            looping = ".looping()" if loop else ""
            defs.append(f"\tpublic static final AnimationDefinition {const} = AnimationDefinition.Builder.withLength({f(length)}){looping}\n"
                        + "\n".join(chains) + "\n\t\t\t.build();")
            ticks = round(length * 20)
            ev = ", ".join(f"\"{n}\", {round(t * 20)}" for t, n in sorted(events))
            common.append(f"\t{const}({ticks}, {str(loop).lower()}, Map.of({ev}))")
            cases.append(f"\t\t\tcase {const} -> {const};")
        anims_java = f"""package net.thesmallthings.hellcraft.client.render.gen;

{HEADER.format(src=self.src)}

import net.minecraft.client.animation.AnimationChannel;
import net.minecraft.client.animation.AnimationDefinition;
import net.minecraft.client.animation.Keyframe;
import net.minecraft.client.animation.KeyframeAnimations;
import net.thesmallthings.hellcraft.entity.boss.gen.{self.java}Anim;

import java.util.Arrays;
import java.util.List;

/** {self.java}'s animations from art/{self.src}, as Minecraft keyframes (Catmull-Rom curves where Blockbench has them). */
public final class {self.java}Animations {{
	private {self.java}Animations() {{
	}}

{chr(10).join(defs)}

	public static AnimationDefinition of({self.java}Anim anim) {{
		return switch (anim) {{
{chr(10).join(cases)}
		}};
	}}

	/** Every animation, in {self.java}Anim's order. */
	public static List<AnimationDefinition> all() {{
		return Arrays.stream({self.java}Anim.values()).map({self.java}Animations::of).toList();
	}}
}}
"""
        enum_java = f"""package net.thesmallthings.hellcraft.entity.boss.gen;

{HEADER.format(src=self.src)}

import net.thesmallthings.hellcraft.entity.boss.BossAnim;

import java.util.Map;

/**
 * {self.java}'s animations as the server sees them: how long each runs (ticks), whether it loops, and its named
 * events (the tick into the animation at which, say, a claw lands), so blows land when the model shows them.
 */
public enum {self.java}Anim implements BossAnim {{
{(","+chr(10)).join(common)};

	public final int ticks;
	public final boolean looping;
	private final Map<String, Integer> events;

	{self.java}Anim(int ticks, boolean looping, Map<String, Integer> events) {{
		this.ticks = ticks;
		this.looping = looping;
		this.events = events;
	}}

	@Override
	public int ticks() {{
		return ticks;
	}}

	@Override
	public boolean looping() {{
		return looping;
	}}

	/** The tick into this animation at which the named event happens. */
	@Override
	public int at(String event) {{
		Integer tick = events.get(event);
		if (tick == null) {{
			throw new IllegalArgumentException(name() + " has no event " + event);
		}}
		return tick;
	}}
}}
"""
        return anims_java, enum_java

    # ---------------------------------------------------------------------------------------------- textures

    def textures(self):
        written = []
        for t in self.doc.get("textures", []):
            source = t.get("source", "")
            if not source.startswith("data:image/png;base64,"):
                raise SystemExit(f"{self.src}: texture {t.get('name')} isn't embedded (save it inside the model in Blockbench)")
            name = t["name"] if t["name"].endswith(".png") else t["name"] + ".png"
            path = os.path.join(TEXTURES, name)
            os.makedirs(TEXTURES, exist_ok=True)
            with open(path, "wb") as out:
                out.write(base64.b64decode(source.split(",", 1)[1]))
            written.append(name)
        return written

    def run(self):
        write(os.path.join(CLIENT, f"{self.java}Mesh.java"), self.mesh())
        anims, enum = self.animations()
        write(os.path.join(CLIENT, f"{self.java}Animations.java"), anims)
        write(os.path.join(COMMON, f"{self.java}Anim.java"), enum)
        textures = self.textures()
        print(f"{self.src}: {len(self.part_names)} parts, {len(self.doc.get('animations', []))} animations, textures {', '.join(textures)}")


def main():
    models = sorted(glob.glob(os.path.join(ART, "*.bbmodel")))
    if not models:
        raise SystemExit("No models in versions/26.3/art")
    for path in models:
        Converter(path).run()


if __name__ == "__main__":
    main()
